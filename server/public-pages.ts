export function registerPublicPages(app: Express) {
  const send = (html: string) => (_req: any, res: any) => {
    res.set("Cache-Control", "public, max-age=3600").type("html").send(html);
  };
  app.get(["/privacy", "/privacy-policy"], send(PRIVACY));
  app.get("/support", send(SUPPORT));
}
